/* ---------------------------------------------------- build options --- */
/* build.py: FELUCCA_<NAME>=0 / 1 in the environment overrides these. Elsewhere: FELUCCA_FM4
 * (core.h: the DIGITAL engine), FELUCCA_ICONS (icons.c, the parameter icons; on by default),
 * FELUCCA_OTA_RAMONLY (ota.c). */
#ifndef FELUCCA_FLASH
#define FELUCCA_FLASH 1          /* flash driver + storage.c: settings, projects, user presets */
#endif
#ifndef FELUCCA_OTA
#define FELUCCA_OTA 1            /* M-UPGRADE update entry and the editor SysEx; needs FELUCCA_FLASH */
#endif
#ifndef FELUCCA_OTA_DRYRUN
#define FELUCCA_OTA_DRYRUN 0     /* 1 = stage, ask "success", then undo: no record, no reset */
#endif
#ifndef FELUCCA_CDC
#define FELUCCA_CDC 1            /* USB CDC-ACM serial console */
#endif
#ifndef FELUCCA_UAC
#define FELUCCA_UAC 1            /* USB audio input: the master output, 16-bit stereo 44.1 kHz (usb.c) */
#endif
#ifndef FELUCCA_UAC_TONE
#define FELUCCA_UAC_TONE 0       /* bench: the USB input sends test triangles instead of the music */
#endif
#ifndef FELUCCA_DISK
#define FELUCCA_DISK 1           /* M-Vave-OP1: MENU > USB DISK, the projects on a read-only USB drive (usbdisk.c) */
#endif
#ifndef FELUCCA_UART
#define FELUCCA_UART 1           /* TRS MIDI IN on UART1 / PH8 */
#endif
#ifndef FELUCCA_ID
#define FELUCCA_ID "FM-1_953"    /* package identity (build.py PRODUCT: the .fwsc marker string; M-Vave-OP1 v0.1: FM-1_900) */
#endif
#ifndef FELUCCA_CPU2
#define FELUCCA_CPU2 1           /* 1: the second core is built in and renders some of the parts when MENU > SYSTEM >
                                  * 2ND CORE is ON (BETA; OFF by default: one core, as before; hal/fm1_cpu1.h, fx.c
                                  * mix_block, cpu2.c). 0 (FELUCCA_CPU2=0 build.py): none of it (no core 1 stack, waiting
                                  * loop, sums or menu row). (The same default: core.h) */
#endif
#define FM1_CPU1 FELUCCA_CPU2      /* hal/fm1_cpu1.h: the second core is built in (fm1_irq.h hands its faults to it);
                                    * defined, 0 or 1, every reset holds it first (hal/fm1_sys.h) */
#define FM1_CPU1_FALLBACK 1        /* a misread, a fault or a late job: core 1 retired, one core until power-off (and
                                    * cpu2.c turns 2ND CORE off), not a restart */
#ifndef FELUCCA_VERSION
#define FELUCCA_VERSION "v1.5.1" /* shown in the menu, the console and the editor; build.py --release X.Y */
#endif
#if FELUCCA_DISK && !FELUCCA_OTA
#error "FELUCCA_DISK needs FELUCCA_OTA (the transport stop, the flash)"
#endif
#if FELUCCA_OTA && !FELUCCA_FLASH
#error "FELUCCA_OTA needs FELUCCA_FLASH"
#endif

