# M-Vave-OP1: firmware/src/j6phrase_data.h, ARP 3's RHY: the Roland J-6's 108 phrases (owner's manual 1.02, Phrase List:
# 9 STYLE x 12 VARIATION, https://static.roland.com/manuals/J-6_manual_v102/eng/28645808.html), played into the
# J-6 Phrase Log from a J-6 holding a four-note chord (G3 A#3 D4 F4) and corrected there (assets/j6-phrases.json):
#   python3 tools/gen_j6phrase.py assets/j6-phrases.json > firmware/src/j6phrase_data.h
# The recordings started at their first note: the J-6's first note came about a tick late (undone), and a rest before
# it was not recorded. The rest is put back from the Phrase List where it notates the phrase (STYLE 4, 5), is none
# where the cycle leaves no room for it, and is a best guess by the metre for 23 of STYLE 6 .. 9 (leadSource
# "geschätzt" in the JSON, its other candidates in leadOptions).
import json
import sys

NSTYLE, NVAR = 9, 12


def main():
    d = json.load(open(sys.argv[1], encoding='utf-8'))
    assert d.get('format') == 'jan3000-j6-phrases' and d.get('grid') == 24, 'a J-6 Phrase Log export, 24 PPQN'
    by = {(p['style'], p['variation']): p for p in d['phrases']}
    assert sorted(by) == [(s, v) for s in range(1, NSTYLE + 1) for v in range(1, NVAR + 1)], 'all 108 phrases'
    ev, idx = [], []
    for s in range(1, NSTYLE + 1):
        for v in range(1, NVAR + 1):
            p = by[(s, v)]
            cyc = p['cycle']
            es = sorted(p['events'], key=lambda e: (e['t'], e['deg'], e['oct']))
            assert 1 <= len(es) <= 255 and 2 <= cyc <= 511, (s, v)
            idx.append((len(ev), len(es), cyc))
            for e in es:
                t, ln, dg, oc, ac = e['t'], e['len'], e['deg'], e['oct'], e['acc']
                assert 0 <= t < cyc and 1 <= ln <= 511 and 0 <= dg <= 3 and 0 <= oc <= 3 and ac in (0, 1), (s, v, e)
                ev.append(t | ln << 9 | dg << 18 | oc << 20 | ac << 22)
    assert len(ev) < 65536
    o = sys.stdout
    o.write('/* SPDX-License-Identifier: GPL-3.0-only\n * Copyright (C) 2026 M-Vave-OP1 contributors */\n')
    o.write('/* M-Vave-OP1, ARP 3 (j6phrase.c): the Roland J-6\'s 108 phrases (owner\'s manual 1.02, Phrase List), as a J-6\n'
            ' * plays them over a four-note chord; generated by tools/gen_j6phrase.py from assets/j6-phrases.json: do not\n'
            ' * edit. A phrase (J6PH[(STYLE - 1) * 12 + VARIATION - 1]): its first note in J6PH_EV, how many, its cycle in\n'
            ' * ticks of 24 PPQN (96 a bar), the rest before its first note included. A note: t (bits 0..8, ticks into the\n'
            ' * cycle), len (9..17, ticks), the chord tone (18..19, 0 the lowest of the four), the octave above it (20..21),\n'
            ' * an accent (22); sorted by t */\n')
    o.write('#define J6PH_N %du\n#define J6PH_NEV %du\n' % (len(idx), len(ev)))
    o.write('static const uint32_t J6PH_EV[J6PH_NEV] = {\n')
    for k in range(0, len(ev), 8):
        o.write('    ' + ' '.join('%d,' % x for x in ev[k:k + 8]) + '\n')
    o.write('};\nstatic const struct { uint16_t first, cycle; uint8_t n, rsv; } J6PH[J6PH_N] = {\n')
    for k in range(0, len(idx), 4):
        o.write('    ' + ' '.join('{%d, %d, %d, 0},' % (f, c, n) for f, n, c in idx[k:k + 4]) + '\n')
    o.write('};\n')


if __name__ == '__main__':
    main()
