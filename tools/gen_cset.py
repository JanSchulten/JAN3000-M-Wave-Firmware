# M-Vave-OP1: firmware/src/cset_data.h, SCL > CSET's 100 chord sets, from the Roland J-6 owner's manual's Chord Set
# List (version 1.02, https://static.roland.com/manuals/J-6_manual_v102/eng/28645807.html), saved as HTML:
#   python3 tools/gen_cset.py PAGE.html > firmware/src/cset_data.h
# Each set: its genre and twelve chords (keys C .. B), each its name and up to four notes as the list voices them.
import re
import sys
from html.parser import HTMLParser

NN = {'C': 0, 'C#': 1, 'Db': 1, 'D': 2, 'D#': 3, 'Eb': 3, 'E': 4, 'F': 5, 'F#': 6, 'Gb': 6, 'G': 7, 'G#': 8,
      'Ab': 8, 'A': 9, 'A#': 10, 'Bb': 10, 'B': 11}
GENRE = {'PopSynth': 'POP/SYNTH', 'CinematicSynthwave': 'CINEMA/SYNTHWAVE', 'CinematicHouse': 'CINEMA/HOUSE',
         'New AgeCinematic': 'NEW AGE/CINEMA', 'SynthwaveHouse': 'SYNTHWAVE/HOUSE', 'HouseTechno': 'HOUSE/TECHNO',
         'GospelR&B': 'GOSPEL/R&B', 'JazzBossa': 'JAZZ/BOSSA', 'Neo-Soul': 'NEO SOUL', 'Cinematic': 'CINEMATIC'}
SHORT = {'POP': 'POP', 'JAZZ': 'JAZZ', 'BLUES': 'BLUES', 'TRAD MAJ': 'TRAD', 'TRAD MIN': 'TRADm', 'TRAD MIN 2': 'TRADm2',
         'POP MIN': 'POPm', 'JAZZ MIN': 'JAZZm', 'OCT STACK': 'OCT', '4TH STACK': '4TH', '5TH STACK': '5TH',
         'UTILITY': 'UTIL', 'POP/SYNTH': 'P/SYN', 'CINEMATIC': 'CINE', 'CINEMATIC/SYNTHWAVE': 'C/SYN',
         'CINEMATIC/HOUSE': 'C/HSE', 'NEW AGE/CINEMATIC': 'N.AGE', 'SYNTHWAVE': 'SYNWV', 'SYNTHWAVE/HOUSE': 'S/HSE',
         'TRANCE': 'TRNCE', 'HOUSE': 'HOUSE', 'JAZZ HOUSE': 'J/HSE', 'HOUSE/TECHNO': 'H/TEC', 'TECHNO': 'TECNO',
         'EDM': 'EDM', 'GOSPEL/R&B': 'GOSPL', 'LOFI R&B': 'LOFI', 'FUNK': 'FUNK', 'NEO SOUL': 'NEO', 'JAZZ/BOSSA': 'J/BOS',
         'BOSSA NOVA': 'BOSSA', 'CLASSICAL': 'CLASS', 'MODERN': 'MODRN'}   # (a card's value: five or six letters)
FIX = {'F#FM7': 'F#M7'}                          # (the list's typo: its notes are F#M7's)
STACK = {14: 'oct', 15: '4th', 16: '5th'}        # (the stack sets name no chords: the key and the stack)
KEYS = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']


class Rows(HTMLParser):
    def __init__(self):
        super().__init__()
        self.rows, self.cur, self.cell = [], None, None

    def handle_starttag(self, tag, attrs):
        if tag == 'tr':
            self.cur = []
        elif tag in ('td', 'th'):
            self.cell = []

    def handle_endtag(self, tag):
        if tag in ('td', 'th') and self.cell is not None and self.cur is not None:
            self.cur.append(re.sub(r'\s+', ' ', ''.join(self.cell)).strip())
            self.cell = None
        elif tag == 'tr' and self.cur is not None:
            self.rows.append(self.cur)
            self.cur = None

    def handle_data(self, data):
        if self.cell is not None:
            self.cell.append(data)


def midi(n):
    m = re.match(r'([A-G][#b]?)(\d)$', n)
    return 12 * (int(m.group(2)) + 1) + NN[m.group(1)]


def main():
    p = Rows()
    p.feed(open(sys.argv[1], encoding='utf-8').read())
    sets, i = [], 0
    while i < len(p.rows):
        r = p.rows[i]
        if len(r) == 14 and re.match(r'^\d+$', r[0]):
            no, genre = int(r[0]), r[1].strip()
            notes = []
            for c in p.rows[i + 1]:
                ns = re.findall(r'[A-G][#b]?\d', c)
                assert ''.join(ns) == c.replace(' ', ''), (no, c)
                notes.append(sorted(set(midi(x) for x in ns)))
            names = [FIX.get(x.replace(' ', ''), x.replace(' ', '')) for x in r[2:]]
            if no in STACK:
                names = [k + STACK[no] for k in KEYS]
            sets.append((no, GENRE.get(genre, genre.upper()), names, notes))
            i += 2
            continue
        i += 1
    assert [s[0] for s in sets] == list(range(1, 101)), 'the 100 sets'
    genres, quals = [], []
    for s in sets:
        if s[1] not in genres:
            genres.append(s[1])
    names = []
    for s in sets:
        row = []
        for x in s[2]:
            m = re.match(r'([A-G])([#b]?)(.*)$', x)
            assert m, x
            q = m.group(3)
            if q not in quals:
                quals.append(q)
            row.append((NN[m.group(1)] | {'': 0, '#': 0x10, 'b': 0x20}[m.group(2)], quals.index(q)))
        names.append(row)
    assert len(quals) < 256 and all(len(n) <= 4 and all(29 <= x <= 127 for x in n) for s in sets for n in s[3])
    o = sys.stdout
    o.write('/* SPDX-License-Identifier: GPL-3.0-only\n * Copyright (C) 2026 M-Vave-OP1 contributors */\n')
    o.write('/* M-Vave-OP1, SCL > CSET (cset.c): the 100 chord sets of the Roland J-6 owner\'s manual\'s Chord Set List\n'
            ' * (version 1.02), generated by tools/gen_cset.py: do not edit. A set: its genre and twelve chords, keys C .. B;\n'
            ' * a chord: up to four notes, ascending (0: none), as the list voices them, and its name: the root\'s letter\n'
            ' * (bits 0..3, 0 C .. 11 B, then 0x10 a sharp, 0x20 a flat) and its quality (CSET_QUAL) */\n')
    o.write('#define CSET_N 100u\n#define CSET_NQ %du\n#define CSET_NG %du\n' % (len(quals), len(genres)))
    o.write('static const uint8_t CSET_NOTE[CSET_N][12][4] = {\n')
    for s in sets:
        o.write('    {' + ', '.join('{' + ', '.join(str(x) for x in (n + [0] * (4 - len(n)))) + '}' for n in s[3]) + '},\n')
    o.write('};\nstatic const uint8_t CSET_NAME[CSET_N][12][2] = {\n')
    for row in names:
        o.write('    {' + ', '.join('{%d, %d}' % r for r in row) + '},\n')
    o.write('};\nstatic const char *const CSET_QUAL[CSET_NQ] = {\n')
    for k in range(0, len(quals), 8):
        o.write('    ' + ' '.join('"%s",' % q for q in quals[k:k + 8]) + '\n')
    o.write('};\nstatic const char *const CSET_GENRE[CSET_NG] = {\n')
    for k in range(0, len(genres), 4):
        o.write('    ' + ' '.join('"%s",' % g for g in genres[k:k + 4]) + '\n')
    o.write('};\nstatic const char *const CSET_GENRE_S[CSET_NG] = {   /* (shorter: SCL > CSET\'s KNOB 3 card) */\n')
    for k in range(0, len(genres), 8):
        o.write('    ' + ' '.join('"%s",' % SHORT[g] for g in genres[k:k + 8]) + '\n')
    o.write('};\nstatic const uint8_t CSET_GENRE_OF[CSET_N] = {\n')
    for k in range(0, 100, 20):
        o.write('    ' + ' '.join('%d,' % genres.index(s[1]) for s in sets[k:k + 20]) + '\n')
    o.write('};\n')


if __name__ == '__main__':
    main()
