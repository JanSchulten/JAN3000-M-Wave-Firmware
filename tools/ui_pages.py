"""M-Vave-OP1: where the UI code asks which page it is on. Every reference to a page's panel kind (GR_* in
firmware/src, params.c's enum) outside its enum and PAGES[], grouped by the function that holds it: the places a page
is special-cased, which the page hooks (PAGES[].desc and .flags in params.c, GRAPH_OPS in ui_graph.c) take over one
page at a time. Writes Markdown: the functions by how many cases they hold, then each GR_* with its places.
  tools/ui_pages.py [OUT.md]          (default: print)"""
import collections
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "firmware" / "src"
# a function's first line: at column 0, a type and a name, '(' and no ';' (a prototype) on it
FDEF = re.compile(r"^(?:static\s+|inline\s+|FM1_FPU\s+|__attribute__\(\([^)]*\)\)\s+)*[A-Za-z_][\w\s*]*?\b([A-Za-z_]\w*)\s*\(")


def kinds():
    """the GR_* names, in the enum's order (its comments may name one again: once each)"""
    txt = (SRC / "params.c").read_text()
    body = re.search(r"enum \{ (GR_NONE.*?) \};", txt, re.S).group(1)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    return [g for g in dict.fromkeys(re.findall(r"\bGR_[A-Z0-9_]+\b", body)) if g != "GR_N"]   # (GR_N: the count)


def places(names):
    """{GR_*: Counter((file, function))}: every reference outside the enum and PAGES[] (a table's rows: its name)"""
    out = collections.defaultdict(collections.Counter)
    for path in sorted(SRC.glob("*.c")):
        cur, in_enum = None, False
        for line in path.read_text(encoding="utf-8", errors="replace").split("\n"):
            if line[:1] and line[0] not in " \t#/*}{":
                m = FDEF.match(line)
                if m and not line.rstrip().endswith(";"):
                    cur = m.group(1)
                elif "=" in line or "[" in line:     # a table at file level: its rows are its own
                    t = re.search(r"\b([A-Za-z_]\w*)\s*\[", line)
                    cur = "(" + (t.group(1) if t else "table") + ")"
            if line.startswith("enum { GR_NONE"):
                in_enum = True
            if in_enum:
                in_enum = "};" not in line
                continue
            if cur in ("(PAGES)", "(GRAPH_OPS)", "graph_ops"):   # (the hooks themselves: a page's own rows)
                continue
            code = re.sub(r"/\*.*?(\*/|$)", "", line)
            for g in re.findall(r"\bGR_[A-Z0-9_]+\b", code):
                if g in names:
                    out[g][(path.name, cur or "?")] += 1
    return out


def report(names, where):
    per_fn = collections.Counter()
    for g in names:
        for k, n in where[g].items():
            per_fn[k] += n
    total = sum(per_fn.values())
    L = ["# UI page special cases", "",
         "Generated by `tools/ui_pages.py`: every place in `firmware/src` that asks for a page's panel kind (`GR_*`),",
         "outside its enum and `PAGES[]`. Each is a page special-cased in shared code; the page hooks",
         "(`PAGES[].desc` and `.flags` in params.c, `GRAPH_OPS` in ui_graph.c) take them over one page at a time.", "",
         f"**{total} references** in **{len(per_fn)} functions**, for {len(names)} panel kinds.", "",
         "## The functions that hold them", "", "| References | File | Function |", "| ---: | --- | --- |"]
    L += [f"| {n} | `{f}` | `{fn}` |" for (f, fn), n in per_fn.most_common()]
    L += ["", "## Each panel kind", "", "| Kind | References | Where |", "| --- | ---: | --- |"]
    for g in sorted(names, key=lambda g: -sum(where[g].values())):
        w = where[g]
        L.append(f"| `{g}` | {sum(w.values())} | " +
                 (", ".join(f"`{fn}` ({f}{' x' + str(n) if n > 1 else ''})" for (f, fn), n in w.most_common()) or "-") + " |")
    return "\n".join(L) + "\n"


def main(argv):
    names = kinds()
    md = report(names, places(names))
    if len(argv) > 1:
        Path(argv[1]).write_text(md)
    else:
        sys.stdout.write(md)


if __name__ == "__main__":
    main(sys.argv)
